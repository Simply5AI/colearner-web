describe('B10 school policy controls (S6) and effective view', () => {
  const policyPuts = () => mock.requests.filter(request => request.method === 'PUT')
  it('loads an older row without the new fields as allowed with 3 hints and explains stricter-wins', async () => {
    install({ scenario: 'under14' })
    view(<SchoolPolicyScreen schoolId="school-a" />)
    await screen.findByRole('group', { name: 'Ask Co and homework help' })
    expect(screen.getByRole('checkbox', { name: 'Allow Ask Co questions' })).toBeChecked()
    expect(screen.getByRole('checkbox', { name: 'Allow homework help' })).toBeChecked()
    expect(screen.getByLabelText('Hints per homework problem')).toHaveValue('3')
    expect(screen.getByText(/If a parent turns this off it stays off for that child; the lower hint limit wins\./)).toBeInTheDocument()
  })
  it('saving without touching the controls sends no new keys, so an older platform keeps accepting it', async () => {
    const user = userEvent.setup()
    install({ scenario: 'under14' })
    view(<SchoolPolicyScreen schoolId="school-a" />)
    await screen.findByRole('group', { name: 'Ask Co and homework help' })
    await user.click(screen.getByRole('button', { name: 'Save reviewed restrictions' }))
    await waitFor(() => expect(policyPuts()).toHaveLength(1))
    const settings = (nth(policyPuts(), 0).body as { settings: Record<string, unknown> }).settings
    expect(Object.keys(settings)).not.toContain('askCoAllowed')
    expect(Object.keys(settings)).not.toContain('homeworkHintsMax')
    expect((nth(policyPuts(), 0).body as { expectedRevision: number }).expectedRevision).toBe(3)
  })
  it('saves the three edited values with the reviewed revision and confirms the saved state', async () => {
    const user = userEvent.setup()
    install({ scenario: 'under14' })
    view(<SchoolPolicyScreen schoolId="school-a" />)
    await screen.findByRole('group', { name: 'Ask Co and homework help' })
    await user.click(screen.getByRole('checkbox', { name: 'Allow Ask Co questions' }))
    await user.selectOptions(screen.getByLabelText('Hints per homework problem'), '1')
    await user.click(screen.getByRole('checkbox', { name: 'Allow homework help' }))
    expect(screen.getByLabelText('Hints per homework problem')).toBeDisabled()
    expect(screen.getByText(/hint limit is not used while homework help is off/)).toBeInTheDocument()
    await user.click(screen.getByRole('checkbox', { name: 'Allow homework help' }))
    await user.click(screen.getByRole('button', { name: 'Save reviewed restrictions' }))
    await screen.findByText(/School rules saved/)
    const body = nth(policyPuts(), 0).body as { expectedRevision: number; settings: Record<string, unknown> }
    expect(body.expectedRevision).toBe(3)
    expect(body.settings).toMatchObject({ askCoAllowed: false, homeworkHelpAllowed: true, homeworkHintsMax: 1, dailyMinutes: 45, educationPackVersion: null })
    await waitFor(() => expect(screen.getByRole('checkbox', { name: 'Allow Ask Co questions' })).not.toBeChecked())
    expect(screen.getByLabelText('Hints per homework problem')).toHaveValue('1')
  })
  it('loads saved values and offers exactly 0 to 3 hints', async () => {
    install({ scenario: 'under14', policy: 'set' })
    view(<SchoolPolicyScreen schoolId="school-a" />)
    const select = await screen.findByLabelText('Hints per homework problem')
    expect(select).toHaveValue('2')
    expect(within(select).getAllByRole('option').map(option => (option as HTMLOptionElement).value)).toEqual(['0', '1', '2', '3'])
  })
  it('keeps the whole draft after a revision conflict', async () => {
    const user = userEvent.setup()
    install({ scenario: 'under14', policyConflict: true })
    view(<SchoolPolicyScreen schoolId="school-a" />)
    await screen.findByRole('group', { name: 'Ask Co and homework help' })
    await user.selectOptions(screen.getByLabelText('Hints per homework problem'), '0')
    await user.click(screen.getByRole('button', { name: 'Save reviewed restrictions' }))
    await screen.findByText(/Your draft is preserved/)
    expect(screen.getByLabelText('Hints per homework problem')).toHaveValue('0')
    expect(screen.getByRole('alert')).toHaveTextContent(/changed/)
  })
  it('shows effective Ask Co and homework limits only when the platform sends them', () => {
    const settings = { dailyMinutes: 45, sources: [], mediaSources: [], voiceAllowed: false, groupsAllowed: false, educationPackVersion: null }
    const base = { allowedNow: true, remainingSeconds: 600, settings, reasons: [], parentConversationAccess: 'FULL', aiAllowed: true }
    const first = render(<EffectivePolicyView policy={base as never} />)
    expect(screen.queryByText('Ask Co')).not.toBeInTheDocument()
    first.unmount()
    render(<EffectivePolicyView policy={{ ...base, settings: { ...settings, askCoAllowed: false, homeworkHelpAllowed: true, homeworkHintsMax: 1 } } as never} />)
    expect(screen.getByText('Turned off')).toBeInTheDocument()
    expect(screen.getByText('Allowed · up to 1 hints')).toBeInTheDocument()
  })
})
