function nth<T>(list: T[], index: number): T {
  const value = list[index]
  if (value === undefined) throw new Error(`missing item ${index}`)
  return value
}
function install(options: ConversationMockOptions, delay?: Promise<void>) {
  mock = createConversationMock(options)
  vi.stubGlobal('fetch', vi.fn(async (url: string, init?: RequestInit) => {
    if (delay) await delay
    const parsed = new URL(url)
    const reply = mock.handle(init?.method ?? 'GET', parsed.pathname + parsed.search, init?.body ? JSON.parse(String(init.body)) : undefined)
    return new Response(JSON.stringify(reply.body), { status: reply.status })
  }))
}
function view(node: React.ReactNode) {
  const client = new QueryClient({ defaultOptions: { queries: { retry: false }, mutations: { retry: false } } })
  return render(<QueryClientProvider client={client}>{node}</QueryClientProvider>)
}
