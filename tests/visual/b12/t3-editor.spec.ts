import { expect, test, type Page } from '@playwright/test'

/** All data is the development fixture (app/dev/teacher/plans/mock-server.ts); nothing here proves the real platform. */
const noOverflow = (page: Page) => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)
const order = (page: Page) => page.getByTestId('tree-node').evaluateAll(nodes => nodes.map(node => node.getAttribute('data-node-id')))
const editor = (plan: string, topic: string, extra = '') => `/dev/teacher/plans?view=editor&plan=${plan}&topic=${topic}${extra}`

