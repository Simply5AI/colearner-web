test('tree reorder by buttons and by keyboard drag, announced and saved', async ({ page }) => {
  await page.goto(editor('plan-algebra', 'a-topic-1'))
  await expect(page.getByTestId('tree-node')).toHaveCount(4)
  expect(await order(page)).toEqual(['a-phase-1', 'a-topic-1', 'a-topic-2', 'a-phase-2'])
  await page.getByRole('button', { name: 'Move Topic: Simple equations up' }).click()
  await expect(page.getByTestId('tree-announce')).toContainText('Moved Simple equations to position 1 of 2')
  await expect.poll(() => order(page)).toEqual(['a-phase-1', 'a-topic-2', 'a-topic-1', 'a-phase-2'])
  const handle = page.getByRole('button', { name: /^Reorder Topic: Simple equations/ })
  await expect(handle).toHaveAttribute('aria-grabbed', 'false')
  await handle.focus()
  // dnd-kit attaches its keyboard listeners on the next tick after pick-up.
  await page.keyboard.press('Space'); await page.waitForTimeout(150)
  await page.keyboard.press('ArrowDown'); await page.waitForTimeout(150)
  await page.keyboard.press('Space')
  await expect.poll(() => order(page)).toEqual(['a-phase-1', 'a-topic-1', 'a-topic-2', 'a-phase-2'])
})

test('tree: add, rename and remove; a failed save rolls the order back and says so', async ({ page }) => {
  await page.goto(editor('plan-algebra', 'a-topic-1'))
  await page.getByRole('button', { name: 'Add phase' }).click()
  await page.getByLabel('New phase name').fill('Extras'); await page.getByRole('button', { name: 'Add', exact: true }).click()
  await expect(page.getByTestId('tree-node').filter({ hasText: 'Extras' })).toBeVisible()
  await page.getByRole('button', { name: 'Rename' }).click()
  await page.getByLabel('New name').fill('Bonus'); await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByTestId('tree-node').filter({ hasText: 'Bonus' })).toBeVisible()
  await page.getByRole('button', { name: 'Remove', exact: true }).click()
  await expect(page.getByTestId('tree-confirm-remove')).toBeVisible()
  await page.getByRole('button', { name: 'Remove', exact: true }).last().click()
  await expect(page.getByTestId('tree-node').filter({ hasText: 'Bonus' })).toHaveCount(0)
  await page.goto(editor('plan-algebra', 'a-topic-1', '&state=tree-fail'))
  await expect(page.getByTestId('tree-node')).toHaveCount(4)
  await page.getByRole('button', { name: 'Move Topic: Variables down' }).click()
  await expect(page.getByTestId('plan-failure')).toContainText('previous order was restored')
  expect(await order(page)).toEqual(['a-phase-1', 'a-topic-1', 'a-topic-2', 'a-phase-2'])
})

