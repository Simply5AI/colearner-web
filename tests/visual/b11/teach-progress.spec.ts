import { expect, test } from '@playwright/test'
for (const band of ['kids', 'tweens', 'teens']) {
  test(`${band} saved feedback and unavailable voice`, async ({ page }) => {
    await page.goto(`/dev/teach?band=${band}&state=feedback`)
    await expect(page.getByTestId('teach-feedback')).toBeVisible()
    await expect(page.getByTestId('teach-voice-note')).toContainText('speech recognition')
    await expect(page.getByRole('button', { name: /microphone|record/i })).toHaveCount(0)
    if (band === 'teens') await expect(page.getByTestId('taught-it')).toHaveCount(0)
    else await expect(page.getByTestId('taught-it')).toHaveText('Taught it!')
    await page.getByTestId('teach-sources').locator('summary').click()
    await expect(page.getByTestId('teach-sources').getByRole('link', { name: 'Water cycle page' })).toHaveAttribute('href', '/learn/library/material-fixture')
    await expect(page.getByTestId('teach-sources')).toContainText('Warm water can become vapour.')
    await expect(page.getByTestId('missed-points')).toHaveCount(band === 'teens' ? 1 : 0)
    for (const variant of ['buddy', 'spark', 'comet', 'sprout']) await expect(page.locator(`[aria-label="Co identities"] [data-co-variant="${variant}"]`)).toBeVisible()
    await page.screenshot({ path: test.info().outputPath(`${band}-feedback.png`), fullPage: true })
  })
}
test('pending never renders a partial reply', async ({ page }) => {
  await page.goto('/dev/teach?band=kids&state=pending')
  await expect(page.getByTestId('teach-pending')).toBeVisible()
  await expect(page.getByTestId('teach-reply-text')).toHaveCount(0)
  await expect(page.locator('[data-co-state="listening"]')).toHaveCount(0)
})
test('follow-up finishes with saved feedback', async ({ page }) => {
  await page.goto('/dev/teach?band=tweens&state=follow-up')
  await expect(page.getByTestId('follow-up-prompt')).toContainText('vapour cools')
  await page.getByRole('textbox').fill('It makes droplets.')
  await page.getByRole('button', { name: 'Send explanation' }).click()
  await expect(page.getByTestId('teach-feedback')).toBeVisible()
})
test('kid garden excludes percentages and failure lists', async ({ page }) => {
  await page.goto('/dev/progress?band=kids')
  await expect(page.getByTestId('garden-plant')).toBeVisible()
  await page.getByRole('button', { name: /Science/ }).click()
  await expect(page.getByTestId('garden-idea')).toHaveText('Water cycle')
  await expect(page.locator('body')).not.toContainText(/\d+%|failures|Weak spots/)
  await expect(page.getByTestId('export-csv')).toHaveCount(0)
})
test('tween activity with unavailable rewards', async ({ page }) => {
  await page.goto('/dev/progress?band=tweens')
  await expect(page.getByTestId('week-activity')).toContainText('2 sessions')
  await expect(page.getByTestId('rewards-unavailable')).toContainText('Levels and badges arrive in a later release')
  await expect(page.getByTestId('readiness')).toHaveCount(0)
})
test('teen measured evidence and separate suggestions; CSV download', async ({ page }) => {
  await page.goto('/dev/progress?band=teens&state=suggestions')
  await expect(page.getByTestId('readiness')).toHaveText('40% ready')
  await expect(page.getByTestId('weak-spots').getByRole('link', { name: 'Practice' })).toBeVisible()
  await expect(page.getByTestId('co-suggests')).toContainText('Try explaining')
  const downloaded = page.waitForEvent('download')
  await page.getByTestId('export-csv').click()
  expect((await downloaded).suggestedFilename()).toBe('progress.csv')
})
test('insufficient, empty, denied and mobile RTL', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/dev/progress?band=teens&state=insufficient&dir=rtl')
  await expect(page.getByTestId('readiness-pending')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: test.info().outputPath('teen-rtl-mobile.png'), fullPage: true })
  await page.goto('/dev/progress?band=kids&state=empty')
  await expect(page.getByRole('link', { name: 'Go to my pages' })).toBeVisible()
  await page.goto('/dev/teach?state=denied')
  await expect(page.getByRole('heading', { name: 'You cannot open this' })).toBeVisible()
})
